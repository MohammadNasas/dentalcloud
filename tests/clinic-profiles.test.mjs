import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { PGlite } from '@electric-sql/pglite'
import { setup, asUser, ids, denied } from './helpers/securityFixture.mjs'
const sql = name => readFile(new URL(`../supabase/${name}.sql`, import.meta.url), 'utf8')

test('profiles enforce assigned-patient finance, shared calendar and owner administration', async t => {
  const db = new PGlite(); t.after(() => db.close())
  await setup(db)
  await db.exec(await sql('subscription_enforcement'))
  await db.exec(await sql('clinic_expenses'))
  await db.exec(await sql('clinic_profiles'))
  await db.exec(await sql('clinic_profiles'))
  await db.exec(await sql('clinic_profile_lab_access'))
  await db.exec(await sql('clinic_profile_lab_access'))
  const other = '40000000-0000-0000-0000-000000000003'
  const recordA = '50000000-0000-0000-0000-000000000001'
  const recordOther = '50000000-0000-0000-0000-000000000002'
  const paymentOther = '60000000-0000-0000-0000-000000000001'
  const appointment = '70000000-0000-0000-0000-000000000001'
  const labMine = '80000000-0000-0000-0000-000000000001'
  const labOther = '80000000-0000-0000-0000-000000000002'
  const labLegacy = '80000000-0000-0000-0000-000000000003'
  await db.query(`update public.clinics set data=data || '{"paid":true,"subscriptionProvider":"manual","paidThrough":"2099-01-01"}' where id=$1`, [ids.clinicA])
  await db.query('insert into public.clinic_profiles(user_id,clinic_id) values($1,$2)', [ids.member,ids.clinicA])
  await db.query(`update public.patients set data=data || jsonb_build_object('assignedDoctorId',$1::text,'openingBalance',70) where id=$2`, [ids.member,ids.patientA])
  await db.query(`insert into public.patients(id,clinic_id,data) values($1,$2,$3)`, [other,ids.clinicA,JSON.stringify({ name:'Other patient', complaint:'Pain', assignedDoctorId:ids.ownerA, openingBalance:999, history:{medical:{diabetes:true},balance:777},orthodontics:{totalCost:555,diagnosis:'Crowding'} })])
  for (const [id,patientId,price] of [[recordA,ids.patientA,35],[recordOther,other,999]]) await db.query('insert into public.tooth_records(id,clinic_id,data) values($1,$2,$3)', [id,ids.clinicA,JSON.stringify({patientId,price,itemKey:'composite',kind:'treatment',status:'done'})])
  await db.query('insert into public.payments(id,clinic_id,data) values($1,$2,$3)',[paymentOther,ids.clinicA,JSON.stringify({patientId:other,amount:999})])
  await db.query(`update public.clinics set data=data || $1::jsonb where id=$2`, [JSON.stringify({ labs:[{id:'lab',name:'Test lab',phone:'123',balance:9999}], revenue:8888 }),ids.clinicA])
  for (const [id,patientId] of [[labOther,other],[labLegacy,null]]) await db.query('insert into public.lab_orders(id,clinic_id,data) values($1,$2,$3)',[id,ids.clinicA,JSON.stringify({patientId,price:999,status:'sent'})])
  const rpc = async (name,args=[]) => (await db.query(`select public.${name}(${args.map((_,i)=>`$${i+1}`).join(',')}) result`,args)).rows[0].result
  const rows = async table => (await rpc('clinic_profile_rows',[table])).rows.filter(r=>!r._restricted)
  const save = (table,data) => rpc('clinic_profile_save',[table,JSON.stringify(data)])
  await asUser(db,ids.member)
  assert.equal((await rpc('clinic_profile_context')).user.isClinicOwner,false)
  const staffClinic = (await rpc('clinic_profile_context')).clinic
  assert.deepEqual(staffClinic.labs,[{id:'lab',name:'Test lab',phone:'123'}])
  assert.equal(staffClinic.revenue,undefined)
  for (const table of ['patients','tooth_records','payments','appointments','clinics','clinic_expenses']) assert.equal((await db.query(`select * from public.${table}`)).rows.length,0,`direct ${table} denied`)
  const patients = await rows('patients')
  const mine = patients.find(p=>p.id===ids.patientA), theirs=patients.find(p=>p.id===other)
  assert.equal(mine.openingBalance,70); assert.equal(mine.canViewFinance,true)
  assert.equal(theirs.complaint,'Pain'); assert.equal(theirs.canViewFinance,false)
  assert.equal(theirs.openingBalance,undefined); assert.equal(theirs.history.balance,undefined)
  assert.equal(theirs.orthodontics.totalCost,undefined); assert.equal(theirs.orthodontics.diagnosis,'Crowding')
  assert.equal((await rows('tooth_records')).find(r=>r.id===recordOther).price,undefined)
  assert.equal((await rows('payments')).length,0)
  assert.equal((await rows('lab_orders')).length,0,'other patients and unassigned legacy orders stay private')
  await denied(save('lab_orders',{id:labOther,patientId:other,price:10,status:'sent'}))
  await denied(save('lab_orders',{id:labLegacy,price:10,status:'sent'}))
  const lab = await save('lab_orders',{id:labMine,patientId:ids.patientA,price:30,paid:10,status:'sent',labName:'Test lab',createdBy:ids.ownerA})
  assert.equal(lab.createdBy,ids.member)
  assert.equal(lab.price,30)
  assert.equal((await rows('lab_orders')).length,1)
  assert.equal((await save('lab_orders',{...lab,status:'received'})).status,'received')
  await denied(save('lab_orders',{...lab,patientId:other}))
  await denied(save('lab_orders',{...lab,patientId:ids.patientB}))
  await db.query('delete from public.lab_orders where id=$1',[labMine])
  assert.equal((await rows('lab_orders')).length,1,'direct staff delete cannot remove orders')
  assert.deepEqual(await rows('appointments'),[], 'empty calendars paginate correctly')
  await denied(db.query('insert into storage.objects(id,bucket_id,name) values(gen_random_uuid(),$1,$2)', ['patient-images',`${ids.clinicA}/${other}/forbidden.jpg`]))
  await db.query('insert into storage.objects(id,bucket_id,name) values(gen_random_uuid(),$1,$2)', ['patient-images',`${ids.clinicA}/${ids.patientA}/allowed.jpg`])
  await denied(rpc('clinic_profile_assign',[other,ids.member]))
  await denied(save('patients',{id:other,assignedDoctorId:ids.member,name:'claim'}))
  await denied(save('payments',{id:paymentOther,patientId:other,amount:0}))
  await denied(save('patients',{id:ids.patientB,name:'cross clinic'}))
  await denied(save('clinic_expenses',{id:recordA,amount:1}))
  await denied(rpc('clinic_profile_rows',['clinic_expenses']))
  await denied(rpc('clinic_profile_can_manage'))
  const saved=await save('tooth_records',{id:recordA,patientId:ids.patientA,price:45,itemKey:'composite',kind:'treatment',status:'done',doctorId:ids.ownerA})
  assert.equal(saved.price,45); assert.equal(saved.doctorId,ids.member)
  await save('patients',{id:ids.patientA,name:'Edited',assignedDoctorId:ids.ownerA,createdBy:ids.ownerA})
  assert.equal((await rows('patients')).find(p=>p.id===ids.patientA).assignedDoctorId,ids.member)
  await save('appointments',{id:appointment,patientId:other,doctorId:ids.ownerA,start:'2027-01-01T09:00:00Z',end:'2027-01-01T09:30:00Z',status:'scheduled'})
  assert.equal((await rows('appointments'))[0].patientId,other)
  await denied(save('tooth_records',{id:recordA,patientId:other,price:0}))
  await asUser(db,ids.ownerA)
  assert.equal((await rpc('clinic_profile_context')).user.isClinicOwner,true)
  assert.equal((await db.query('select * from public.payments')).rows[0].data.amount,999)
  await rpc('clinic_profile_assign',[other,ids.member])
  await asUser(db,ids.member)
  assert.equal((await rows('payments'))[0].amount,999)
  assert.equal((await rows('lab_orders')).length,2,'lab visibility follows patient assignment')
  await asUser(db,ids.ownerA)
  await rpc('clinic_profile_assign',[other,ids.ownerA])
  await asUser(db,ids.member)
  assert.equal((await rows('payments')).length,0)
  assert.equal((await rows('lab_orders')).length,1)
  await asUser(db,'','service_role')
  await db.query("update public.clinics set data=data || '{\"paidThrough\":\"2000-01-01\"}' where id=$1",[ids.clinicA])
  await asUser(db,ids.member)
  await denied(save('patients',{id:ids.patientA,name:'Expired'}))
  await denied(save('lab_orders',{...lab,status:'completed'}))
  assert.equal((await rows('patients')).length,2,'expired profiles retain permitted read access')
  await asUser(db,'','service_role')
  await db.query('update public.clinic_profiles set active=false where user_id=$1',[ids.member])
  await asUser(db,ids.member)
  assert.equal(await rpc('clinic_profile_context'),null)
  await denied(rpc('clinic_profile_rows',['patients']))
  await denied(save('patients',{id:ids.patientA,name:'Blocked'}))
  await asUser(db,ids.outsider)
  assert.equal(await rpc('clinic_profile_context'),null)
  await denied(rpc('clinic_profile_rows',['patients']))
  await asUser(db,'','anon')
  await denied(rpc('clinic_profile_context'))
})
