import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { PGlite } from '@electric-sql/pglite'
import { setup, asUser, ids, denied } from './helpers/securityFixture.mjs'
const sql = name => readFile(new URL(`../supabase/${name}.sql`, import.meta.url), 'utf8')

test('doctors manage other clinicians patients and payments without gaining clinic administration', async t => {
  const db = new PGlite(); t.after(() => db.close())
  await setup(db)
  for (const name of ['subscription_enforcement','clinic_expenses','clinic_profiles','clinic_profile_lab_access','clinic_profile_shared_patients','clinic_profile_shared_patients']) await db.exec(await sql(name))
  await db.query(`update public.clinics set data=data || '{"subscriptionProvider":"manual","paidThrough":"2099-01-01","revenue":99999,"expenses":1234,"settings":{"currency":"USD","privateNote":"secret"}}' where id=$1`,[ids.clinicA])
  await db.query('insert into public.clinic_profiles(user_id,clinic_id) values($1,$2)',[ids.member,ids.clinicA])
  await db.query(`update public.patients set data=data || jsonb_build_object('assignedDoctorId',$1::text,'openingBalance',45) where id=$2`,[ids.ownerA,ids.patientA])
  const rpc = async (name,args=[]) => (await db.query(`select public.${name}(${args.map((_,i)=>`$${i+1}`).join(',')}) result`,args)).rows[0].result
  const save = (table,data) => rpc('clinic_profile_save',[table,JSON.stringify(data)])
  await asUser(db,ids.member)
  const context = await rpc('clinic_profile_context')
  assert.equal(context.user.isClinicOwner,false)
  assert.equal(context.clinic.revenue,undefined)
  assert.equal(context.clinic.expenses,undefined)
  assert.equal(context.clinic.settings.privateNote,undefined)
  const patient = (await rpc('clinic_profile_rows',['patients'])).rows[0]
  assert.equal(patient.canViewFinance,true); assert.equal(patient.openingBalance,45)
  const changed = await save('patients',{id:ids.patientA,name:'Updated by another doctor',assignedDoctorId:ids.member,openingBalance:{amount:30,currency:'USD',confirmed:true},importedHistory:'Reviewed history'})
  assert.equal(changed.name,'Updated by another doctor'); assert.equal(changed.assignedDoctorId,ids.ownerA); assert.equal(changed.openingBalance.amount,30); assert.equal(changed.importedHistory,'Reviewed history')
  const payment = await save('payments',{id:'60000000-0000-0000-0000-000000000005',patientId:ids.patientA,amount:35,doctorId:ids.ownerA,createdBy:ids.ownerA})
  assert.equal(payment.amount,35); assert.equal(payment.doctorId,ids.member); assert.equal(payment.createdBy,ids.member)
  assert.equal((await rpc('clinic_profile_rows',['payments'])).rows[0].amount,35)
  const treatment = await save('tooth_records',{id:'50000000-0000-0000-0000-000000000005',patientId:ids.patientA,price:40,status:'done'})
  assert.equal(treatment.price,40)
  const lab = await save('lab_orders',{id:'80000000-0000-0000-0000-000000000005',patientId:ids.patientA,price:20,paid:5,status:'sent'})
  assert.equal(lab.price,20)
  await db.query('insert into storage.objects(id,bucket_id,name) values(gen_random_uuid(),$1,$2)', ['patient-images',`${ids.clinicA}/${ids.patientA}/other-doctor.jpg`])
  await denied(db.query('insert into storage.objects(id,bucket_id,name) values(gen_random_uuid(),$1,$2)', ['patient-images',`${ids.clinicB}/${ids.patientB}/denied.jpg`]))
  await denied(save('patients',{id:ids.patientB,name:'foreign'}))
  await denied(save('payments',{...payment,id:'60000000-0000-0000-0000-000000000006',patientId:ids.patientB}))
  await denied(save('payments',{...payment,patientId:ids.patientB}))
  for (const table of ['clinic_expenses','clinics','clinic_profile_devices']) await denied(rpc('clinic_profile_rows',[table]))
  await denied(rpc('clinic_profile_can_manage')); await denied(rpc('clinic_profile_assign',[ids.patientA,ids.member]))
  for (const table of ['clinics','clinic_expenses','patients','payments']) assert.equal((await db.query(`select * from public.${table}`)).rows.length,0)
  assert.equal((await db.query(`update public.clinics set data='{}' where id=$1`,[ids.clinicA])).affectedRows,0)
  await asUser(db,'','service_role')
  await db.query('update public.clinic_profiles set active=false where user_id=$1',[ids.member])
  await asUser(db,ids.member)
  await denied(rpc('clinic_profile_rows',['payments'])); await denied(save('payments',payment))
})

test('legacy activation preserves identity and dates; archive is permanent to device grants and never deletes patients', async t => {
  const db = new PGlite(); t.after(() => db.close())
  await setup(db)
  await db.exec("alter table auth.users add column raw_app_meta_data jsonb default '{}'::jsonb")
  for (const name of ['subscription_enforcement','clinic_expenses','clinic_profiles','clinic_profile_legacy_devices','clinic_profile_legacy_devices']) await db.exec(await sql(name))
  const legacy='10000000-0000-0000-0000-000000000010', email=`${legacy}@profiles.dentalcloudapp.com`
  await db.query("insert into public.doctors(id,clinic_id,data,created_at) values($1,$2,'{\"name\":\"Legacy\",\"role\":\"doctor\",\"passwordHash\":\"old-hash\"}','2026-09-01T00:00:00Z')",[legacy,ids.clinicA])
  await db.query('insert into auth.users(id,email,email_confirmed_at,raw_app_meta_data) values($1,$2,now(),$3)',[legacy,email,JSON.stringify({legacyClinicId:ids.clinicA})])
  await db.query(`update public.patients set data=data || jsonb_build_object('assignedDoctorId',$1::text) where id=$2`,[legacy,ids.patientA])
  await asUser(db,ids.member)
  await denied(db.query('select * from public.clinic_profile_devices'))
  await denied(db.query('select public.clinic_profile_finish_legacy($1,$2,$3)',[ids.clinicA,legacy,email]))
  await asUser(db,'','service_role')
  for(let i=0;i<2;i++) await db.query('select public.clinic_profile_finish_legacy($1,$2,$3)',[ids.clinicA,legacy,email])
  const doctor=(await db.query('select * from public.doctors where id=$1',[legacy])).rows[0]
  assert.equal(doctor.data.passwordHash,undefined); assert.equal(doctor.data.profileLoginMode,'device')
  assert.equal(new Date(doctor.created_at).toISOString().slice(0,10),'2026-09-01')
  assert.equal((await db.query('select count(*) from public.clinic_profiles where user_id=$1',[legacy])).rows[0].count,1)
  await asUser(db,ids.ownerB)
  await denied(db.query('select public.clinic_profile_archive($1)',[legacy]))
  await asUser(db,ids.ownerA)
  await denied(db.query('select public.clinic_profile_archive($1)',[ids.ownerA]))
  await db.query('select public.clinic_profile_archive($1)',[legacy])
  assert.equal((await db.query('select * from public.patients where id=$1',[ids.patientA])).rows[0].data.assignedDoctorId,legacy)
  await asUser(db,legacy)
  assert.equal((await db.query('select public.current_clinic_id() cid')).rows[0].cid,null)
  await asUser(db,'','service_role')
  await denied(db.query('select public.clinic_profile_finish_legacy($1,$2,$3)',[ids.clinicA,legacy,email]))
})
